import assert from 'node:assert/strict';
import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { verify } from '../../../src/core/verify.mjs';
const beforeBytes=await readFile(new URL('../semantics/signed-FAIL-native-VERIFIED.json',import.meta.url));
const before=JSON.parse(beforeBytes);
const report=await verify(before.request,before.bundle);
assert.equal(before.report.overall,'VERIFIED');
assert.equal(report.overall,'CONTRADICTED');
assert.equal(report.layers.AUTHENTICITY.status,'VERIFIED');
assert.equal(report.layers.SUBJECT_BINDING.status,'VERIFIED');
assert.equal(report.layers.RECOMPUTATION.status,'REPRODUCED');
assert.equal(report.layers.RECOMPUTATION.semanticOutcome,'VERIFIED');
assert.ok(report.reason_codes.includes('ASSERTED_NATIVE_RESULT_CONTRADICTION'));
assert.deepEqual(report.layers.RECOMPUTATION.nativeResult,before.report.layers.RECOMPUTATION.nativeResult);
assert.deepEqual(report.layers.RECOMPUTATION.nativeCanonicalResult,before.report.layers.RECOMPUTATION.nativeCanonicalResult);
const proof={beforeFixtureSha256:createHash('sha256').update(beforeBytes).digest('hex'),beforeOverall:before.report.overall,afterOverall:report.overall,identicalRequestAndSignedBundle:true,nativeResultPreserved:true,request:before.request,bundle:before.bundle,report};
await writeFile(new URL('signed-FAIL-native-VERIFIED.after.json',import.meta.url),JSON.stringify(proof,null,2)+'\n');
console.log(JSON.stringify({before:proof.beforeOverall,after:proof.afterOverall,beforeFixtureSha256:proof.beforeFixtureSha256,nativeResultPreserved:true}));
